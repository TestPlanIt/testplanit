"use client";

import { useQuery } from "@tanstack/react-query";
import { useMemo } from "react";
import type { ReviewRequestWhereInput } from "~/zenstack/input";
import {
  isReviewAssignee,
  type ReviewAssigneeScope,
  type ReviewEntityType,
} from "~/lib/services/reviewInboxScope";

export interface ReviewAssigneeRow {
  projectId: number;
  assigneeUserId: string | null;
  assigneeRoleId: number | null;
  entityType: ReviewEntityType;
}

export interface UseReviewAssigneeScopeResult {
  /** OR branches that reach the viewer as an assignee; the direct branch alone until the scope lands. */
  assigneeOr: ReviewRequestWhereInput[];
  /** The same predicate for a row already in hand. */
  isAssignee: (row: ReviewAssigneeRow) => boolean;
  isLoading: boolean;
}

/**
 * The viewer's review-assignee scope from `/api/reviews/assignee-scope`:
 * the roles they hold per project, limited to the entity types those roles
 * may approve. Every surface that lists or counts "reviews waiting on me"
 * builds its where-clause from this, so the queue matches what the viewer
 * can actually decide.
 *
 * NOTE: This file lives in `testplanit/hooks/` (custom hooks). It MUST NOT
 * move to `testplanit/lib/hooks/` — that directory is regenerated by
 * `pnpm zenstack generate`.
 */
export function useReviewAssigneeScope(
  userId: string | null | undefined
): UseReviewAssigneeScopeResult {
  const { data, isLoading } = useQuery({
    queryKey: ["review-assignee-scope", userId],
    enabled: !!userId,
    staleTime: 60_000,
    queryFn: async () => {
      const response = await fetch("/api/reviews/assignee-scope");
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      return (await response.json()) as ReviewAssigneeScope & {
        where: ReviewRequestWhereInput[];
      };
    },
  });

  return useMemo(() => {
    const fallback: ReviewRequestWhereInput[] = [
      { assigneeUserId: userId ?? "" },
    ];
    if (!data) {
      return {
        assigneeOr: fallback,
        isAssignee: (row: ReviewAssigneeRow) =>
          row.assigneeUserId === (userId ?? ""),
        isLoading: !!userId && isLoading,
      };
    }
    return {
      assigneeOr: data.where,
      isAssignee: (row: ReviewAssigneeRow) => isReviewAssignee(data, row),
      isLoading: false,
    };
  }, [data, isLoading, userId]);
}
