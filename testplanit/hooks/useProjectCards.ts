"use client";

import { useQuery } from "@tanstack/react-query";
import { useClientQueries } from "@zenstackhq/tanstack-query/react";
import { useSession } from "next-auth/react";
import { useMemo } from "react";
import { useAutomationRunCounts } from "~/hooks/useAutomationRunCounts";
import { apiFetch } from "~/lib/basePath";
import type { ProjectCardStats } from "~/lib/services/projectCardStats";
import {
  processProjectsWithEffectiveMembers,
  type ProcessedProject,
} from "~/utils/projectUtils";
import { schema } from "~/zenstack/schema";

export interface ProjectCardMember {
  id: string;
  name: string;
  image: string | null;
}

export type ProjectCardProject = ProcessedProject & {
  users: { userId: string }[];
};

/**
 * Everything the project card grid on the home and projects pages needs: the
 * projects the viewer can read with their members, the directory those
 * members are drawn from, and each project's live figures.
 *
 * NOTE: lives in `testplanit/hooks/` (custom hooks). It MUST NOT move to
 * `testplanit/lib/hooks/` — that directory is regenerated by zenstack generate.
 */
export function useProjectCards(): {
  projects: ProjectCardProject[];
  members: ProjectCardMember[];
  stats: Record<number, ProjectCardStats>;
  automationRunCounts: Record<number, number>;
  /** False until the project list has come back at least once. */
  isFetched: boolean;
} {
  const { data: session } = useSession();
  const enabled = !!session?.user;

  const { data: allUsers, isFetched: usersFetched } = useClientQueries(
    schema
  ).user.useFindMany(
    {
      where: { isActive: true, isDeleted: false },
      select: { id: true, access: true, name: true, image: true },
      orderBy: { name: "asc" },
    },
    { enabled }
  );

  // ZenStack filters projects by the access rules, which covers explicit
  // assignments and projects with defaultAccessType GLOBAL_ROLE alike.
  const { data: projectsRaw, isFetched: projectsFetched } = useClientQueries(
    schema
  ).projects.useFindMany(
    {
      where: { isDeleted: false },
      orderBy: [{ isCompleted: "asc" }, { name: "asc" }],
      include: {
        _count: {
          select: {
            milestones: { where: { isCompleted: false, isDeleted: false } },
            testRuns: { where: { isCompleted: false, isDeleted: false } },
            sessions: { where: { isCompleted: false, isDeleted: false } },
            repositoryCases: { where: { isDeleted: false } },
          },
        },
        assignedUsers: {
          where: { user: { isActive: true, isDeleted: false } },
          select: { userId: true },
        },
        groupPermissions: {
          select: {
            accessType: true,
            group: {
              select: {
                assignedUsers: {
                  where: { user: { isActive: true, isDeleted: false } },
                  select: { userId: true },
                },
              },
            },
          },
        },
        defaultRole: { select: { id: true, name: true } },
      },
    },
    { enabled, refetchOnWindowFocus: true }
  );

  const projects = useMemo(
    () =>
      processProjectsWithEffectiveMembers(projectsRaw as any, allUsers).map(
        (project) => ({
          ...project,
          users: project.effectiveUserIds.map((id) => ({ userId: id })),
        })
      ),
    [projectsRaw, allUsers]
  );

  const projectIds = useMemo(
    () => projects.map((project) => project.id),
    [projects]
  );
  const { data: stats } = useQuery<Record<number, ProjectCardStats>>({
    queryKey: ["project-card-stats", projectIds],
    queryFn: async () => {
      const response = await apiFetch("/api/projects/card-stats", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ projectIds }),
      });
      if (!response.ok) return {};
      return (await response.json()).stats ?? {};
    },
    enabled: enabled && projectIds.length > 0,
    refetchOnWindowFocus: true,
  });

  const { counts: automationRunCounts } = useAutomationRunCounts(enabled);

  const members = useMemo(
    () =>
      (allUsers ?? []).map((user) => ({
        id: user.id,
        name: user.name,
        image: user.image ?? null,
      })),
    [allUsers]
  );

  return {
    projects,
    members,
    stats: stats ?? {},
    automationRunCounts,
    isFetched: usersFetched && projectsFetched,
  };
}
